"""#132: one-time Summoner backfill SQL (gme/common/SummonerProgress).

python3 scripts/gen_summoner_backfill.py > summoner_backfill.sql
sqlite3 SAVE < summoner_backfill.sql      # after bf-backup; one transaction

Every account gets the Summoner EXP its lifetime player EXP would have paid
under gme::regularQuestGain: lifetime EXP // 3200 Summoner EXP (about Lv 112
at player Lv 999), 1% of that as Summoning Arts EXP for its current element,
and the SummonerLevelMst SP for every level it gains.  RAISE-ONLY and idempotent: a
total already higher is kept, levels never drop, and a second run adds no SP
because it gains no level.  Arm EXP is not backfilled (arm levels have no table).
"""
import json
from pathlib import Path

MST = Path(__file__).resolve().parent.parent / 'deploy' / 'mst'
RATIO = 3200  # gme::kPlayerExpPerSummonerExp


def rows(name):
    data = json.loads((MST / name).read_text())
    return next(iter(data.values())) if isinstance(data, dict) else data


def values(tuples):
    return ',\n'.join('(' + ','.join(str(v) for v in t) + ')' for t in tuples)


def main():
    cum, total = [], 0
    # Row L holds the chunk that takes L-1 to L (Mission.cpp levelUp), so the
    # lifetime EXP at level L is every chunk up to and including row L.
    for r in sorted(rows('user_level_mst.json'), key=lambda r: int(r['D9wXQI2V'])):
        if int(r['D9wXQI2V']) > 1:
            total += int(r['d96tuT2E'])
        cum.append((int(r['D9wXQI2V']), total))
    summoner = sorted((int(r['D9wXQI2V']), int(r['d96tuT2E']), int(r['iIDqD50O']))
                      for r in rows('summoner_level_mst.json'))
    arts = sorted((int(r['iNy0ZU5M']), int(r['D9wXQI2V']), int(r['d96tuT2E']))
                  for r in rows('summoner_element_level_mst.json'))
    top = summoner[-1][1]
    arts_top = {e: max(n for el, _, n in arts if el == e) for e in {a[0] for a in arts}}
    sets = []
    for e in range(1, 7):
        sets.append(f"exp{e} = CASE WHEN user_summoner.element = {e} THEN MAX(user_summoner.exp{e}, MIN(t.elem, {arts_top.get(e, 0)})) ELSE user_summoner.exp{e} END")
    print(f"""-- generated by scripts/gen_summoner_backfill.py
.bail on
BEGIN IMMEDIATE;
CREATE TEMP TABLE bf_ul(lv INTEGER PRIMARY KEY, cum INTEGER);
INSERT INTO bf_ul VALUES
{values(cum)};
CREATE TEMP TABLE bf_sl(lv INTEGER PRIMARY KEY, need INTEGER, sp INTEGER);
INSERT INTO bf_sl VALUES
{values(summoner)};
CREATE TEMP TABLE bf_el(element INTEGER, lv INTEGER, need INTEGER, PRIMARY KEY (element, lv));
INSERT INTO bf_el VALUES
{values(arts)};

-- Lifetime player EXP -> Summoner EXP and Summoning Arts EXP.
CREATE TEMP TABLE bf_target AS
SELECT u.id AS user_id,
       MIN((ul.cum + MAX(u.exp, 0)) / {RATIO}, {top}) AS exp,
       (ul.cum + MAX(u.exp, 0)) / ({RATIO} * 100) AS elem
FROM user_info u JOIN bf_ul ul ON ul.lv = u.level;

INSERT INTO user_summoner (user_id)
SELECT user_id FROM bf_target WHERE exp > 0
ON CONFLICT(user_id) DO NOTHING;

CREATE TEMP TABLE bf_before AS
SELECT s.user_id, s.level AS old_lv FROM user_summoner s JOIN bf_target t ON t.user_id = s.user_id;

UPDATE user_summoner SET
  exp = MAX(user_summoner.exp, t.exp),
  {(','+chr(10)+'  ').join(sets)}
FROM bf_target t WHERE t.user_id = user_summoner.user_id;

-- Levels from the new totals: the summoner curve is monotonic; Summoning Arts
-- are walked in order (first row the total does not reach, minus one).
UPDATE user_summoner SET level = MAX(level,
  (SELECT MAX(lv) FROM bf_sl WHERE need <= user_summoner.exp))
WHERE user_id IN (SELECT user_id FROM bf_target);
""")
    for e in range(1, 7):
        print(f"""UPDATE user_summoner SET level{e} = MAX(level{e}, COALESCE(
  (SELECT MIN(lv) - 1 FROM bf_el WHERE element = {e} AND lv > 1 AND need > user_summoner.exp{e}),
  (SELECT MAX(lv) FROM bf_el WHERE element = {e})))
WHERE element = {e} AND user_id IN (SELECT user_id FROM bf_target);""")
    print("""
-- SP for every level gained, capped like every SP grant.
UPDATE user_summoner SET sp = MIN(sp + COALESCE((SELECT SUM(sl.sp) FROM bf_sl sl, bf_before b
  WHERE b.user_id = user_summoner.user_id AND sl.lv > b.old_lv AND sl.lv <= user_summoner.level), 0), 99999)
WHERE user_id IN (SELECT user_id FROM bf_before);

SELECT 'backfilled', COUNT(*), SUM(level > 1), MAX(level), SUM(sp) FROM user_summoner;
COMMIT;""")


if __name__ == '__main__':
    main()
